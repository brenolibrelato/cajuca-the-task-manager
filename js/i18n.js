export const LANGS = { pt: 'Português', en: 'English' };
const LOCALE = { pt: 'pt-BR', en: 'en-US' };
const STORAGE_KEY = 'cajuca.lang';

function initialLang() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved in DICT) return saved;
  } catch { /* navegador sem storage: segue o idioma do sistema */ }
  const nav = typeof navigator !== 'undefined' && navigator.language;   // testes rodam em Node, sem navegador
  return (nav || 'pt').toLowerCase().startsWith('pt') ? 'pt' : 'en';
}

let lang = initialLang();

export function getLang() { return lang; }

export function setLang(next) {
  if (!(next in DICT)) return;
  lang = next;
  try { localStorage.setItem(STORAGE_KEY, next); } catch { /* ignora */ }
  document.documentElement.lang = LOCALE[lang];
}

export function t(key, vars = {}) {
  const text = DICT[lang][key] ?? DICT.pt[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

// Datas 'YYYY-MM-DD' no formato do idioma (pt: 08/10/2026, en: 10/08/2026)
export function fmtDate(iso) {
  if (!iso) return '';
  const [y, m, d] = iso.slice(0, 10).split('-').map(Number);
  return new Intl.DateTimeFormat(LOCALE[lang], { timeZone: 'UTC' }).format(new Date(Date.UTC(y, m - 1, d)));
}

// Prazo relativo a hoje, em dias de calendário (dayDiff): 0 = "hoje", 3 = "em 3 dias", -3 = "há 3 dias"
export function fmtRelative(days) {
  if (days === 0) return t('rel.today');
  if (days === 1) return t('rel.tomorrow');
  if (days === -1) return t('rel.yesterday');
  return days > 0 ? t('rel.inDays', { n: days }) : t('rel.daysAgo', { n: -days });
}

// Textos estáticos do HTML: data-i18n (texto), data-i18n-title, data-i18n-aria, data-i18n-placeholder
export function applyStatic(root = document) {
  document.documentElement.lang = LOCALE[lang];
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  root.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
}

